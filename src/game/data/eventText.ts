export function eventTitle(event: GameEvent): string {
  return EVENT_TITLES[event.id] ?? event.title;
}

export function choiceLabel(choice: GameEventChoice): string {
  return CHOICE_LABELS[choice.id] ?? choice.label;
}

export function choiceOutcome(choice: GameEventChoice): string {
  return CHOICE_OUTCOMES[choice.id] ?? `${choiceLabel(choice)}之后，本季度指标变化已经写进董事会材料。`;
}

export function eventContext(event: GameEvent): string {
  return EVENT_CONTEXT_OVERRIDES[event.id] ?? CATEGORY_CONTEXTS[event.category];
}

export function factionChoiceEffect(choiceId: string): { faction: FactionId; delta: number } | null {
  return FACTION_CHOICE_EFFECTS[choiceId] ?? null;
}
